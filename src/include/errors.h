#ifndef VISQOL_INCLUDE_ERRORS_H_
#define VISQOL_INCLUDE_ERRORS_H_

#include "absl/base/attributes.h"
#include "absl/status/status.h"
#include "absl/strings/string_view.h"

namespace Visqol {

/**
 * Returns true if @param status is an error generated by Visqol. Returns false
 * if @param status is ok, or not an error generated by Visqol.
 */
[[nodiscard]] bool IsVisqolError(const absl::Status& status);

/**
 * Returns true if @param status indicates that the input audio is too short for
 * Visqol to compute a result.
 */
[[nodiscard]] bool IsInputAudioTooShort(const absl::Status& status);

/**
 * Returns an `absl::Status` to indicate that the input audio is too short for
 * Visqol to compute a result.
 */
absl::Status InputAudioTooShort(absl::string_view message);

}  // namespace Visqol

#endif  // VISQOL_INCLUDE_ERRORS_H_
